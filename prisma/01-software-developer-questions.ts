const prisma = new PrismaClient();

const difficultyMap: Record<Difficulty, PrismaDifficulty> = {
  beginner: PrismaDifficulty.EASY,
  intermediate: PrismaDifficulty.MEDIUM,
  expert: PrismaDifficulty.HARD,
};

async function main() {
  const replaceExisting = process.argv.includes("--replace");
  const categoryRecord = await prisma.category.upsert({
    where: { slug: "software-developer" },
    update: { name: category, group: "Technology", description: "Software Developer interview questions." },
    create: { name: category, slug: "software-developer", group: "Technology", description: "Software Developer interview questions." },
  });
  const subcategory = await prisma.subcategory.upsert({
    where: { categoryId_slug: { categoryId: categoryRecord.id, slug: "software-developer" } },
    update: {},
    create: { name: category, slug: "software-developer", categoryId: categoryRecord.id },
  });

  if (replaceExisting) {
    await prisma.interviewQuestion.deleteMany({ where: { categoryId: categoryRecord.id } });
  }

  for (const item of softwareDeveloperQuestions) {
    const tags = ["software-developer", item.difficulty, item.topic].filter(
      (tag): tag is string => Boolean(tag),
    );
    await prisma.interviewQuestion.upsert({
      where: { slug: item.slug },
      update: {
        question: item.question,
        categoryId: categoryRecord.id,
        subcategoryId: subcategory.id,
        experienceLevel: item.difficulty === "beginner" ? ExperienceLevel.FRESHER : ExperienceLevel.MID_LEVEL,
        difficulty: difficultyMap[item.difficulty],
        interviewType: InterviewType.TECHNICAL,
        shortDescription: `A practical ${item.difficulty} Software Developer interview question.`,
        explanation: item.answer,
        sampleAnswer: item.answer,
        detailedAnswer: item.answer,
        // Now we have actual data for these fields
        keyPoints: item.keyPoints || [],
        commonMistakes: item.commonMistakes || [],
        followUpQuestions: item.followUpQuestions || [],
        tags,
        isPublished: true,
      },
      create: {
        question: item.question,
        slug: item.slug,
        categoryId: categoryRecord.id,
        subcategoryId: subcategory.id,
        experienceLevel: item.difficulty === "beginner" ? ExperienceLevel.FRESHER : ExperienceLevel.MID_LEVEL,
        difficulty: difficultyMap[item.difficulty],
        interviewType: InterviewType.TECHNICAL,
        shortDescription: `A practical ${item.difficulty} Software Developer interview question.`,
        explanation: item.answer,
        sampleAnswer: item.answer,
        detailedAnswer: item.answer,
        keyPoints: item.keyPoints || [],
        commonMistakes: item.commonMistakes || [],
        followUpQuestions: item.followUpQuestions || [],
        tags,
        isPublished: true,
      },
    });
  }

  console.log(`Imported ${softwareDeveloperQuestions.length} Software Developer questions.`);
}

