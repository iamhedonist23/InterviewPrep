async function seedJava() {
  const category = await prisma.studyCategory.upsert({
    where: { slug: "java" },
    update: {
      name: "Java",
      description: "Java programming from beginner fundamentals through advanced JVM, concurrency, collections, APIs, testing, performance, and interview topics.",
      icon: "JAVA",
      isPublished: true,
      sortOrder: 0,
    },
    create: {
      name: "Java",
      slug: "java",
      description: "Java programming from beginner fundamentals through advanced JVM, concurrency, collections, APIs, testing, performance, and interview topics.",
      icon: "JAVA",
      isPublished: true,
      sortOrder: 0,
    },
  });

  // Keep all topics in one module here so the generated files can be imported
  // directly and the DB upsert path is unambiguous. If your existing Java
  // curriculum has module/path metadata, replace only this grouping layer.
  const path = await prisma.studyPath.upsert({
    where: {
      categoryId_level: {
        categoryId: category.id,
        level: StudyLevel.BEGINNER,
      },
    },
    update: {
      name: "Java Complete Learning Path",
      description: "Beginner to advanced Java learning path.",
      level: StudyLevel.BEGINNER,
      isPublished: true,
      sortOrder: 0,
    },
    create: {
      categoryId: category.id,
      name: "Java Complete Learning Path",
      slug: "complete",
      description: "Beginner to advanced Java learning path.",
      level: StudyLevel.BEGINNER,
      isPublished: true,
      sortOrder: 0,
    },
  });

  const module = await prisma.studyModule.upsert({
    where: {
      studyPathId_slug: {
        studyPathId: path.id,
        slug: "java-topics",
      },
    },
    update: {
      title: "Java Topics",
      description: "Java concepts and interview preparation topics.",
      isPublished: true,
      sortOrder: 0,
    },
    create: {
      studyPathId: path.id,
      title: "Java Topics",
      slug: "java-topics",
      description: "Java concepts and interview preparation topics.",
      isPublished: true,
      sortOrder: 0,
    },
  });

  for (let index = 0; index < javaTopics.length; index += 1) {
    const topicSeed = javaTopics[index];

    const savedTopic = await prisma.studyTopic.upsert({
      where: {
        categoryId_slug: {
          categoryId: category.id,
          slug: topicSeed.slug,
        },
      },
      update: {
        title: topicSeed.title,
        moduleId: module.id,
        seoDescription: topicSeed.description,
        estimatedMinutes: topicSeed.estimatedMinutes,
        isPublished: true,
        sortOrder: index,
      },
      create: {
        categoryId: category.id,
        moduleId: module.id,
        title: topicSeed.title,
        slug: topicSeed.slug,
        seoDescription: topicSeed.description,
        estimatedMinutes: topicSeed.estimatedMinutes,
        isPublished: true,
        sortOrder: index,
        prerequisiteIds: [],
        relatedTopicIds: [],
      },
    });

    for (let sectionIndex = 0; sectionIndex < (topicSeed.sections ?? []).length; sectionIndex += 1) {
      const section = topicSeed.sections![sectionIndex];

      await prisma.studyTopicSection.upsert({
        where: { id: `${savedTopic.id}-section-${sectionIndex}` },
        update: {
          title: section.title,
          content: section.content,
          sortOrder: sectionIndex,
        },
        create: {
          id: `${savedTopic.id}-section-${sectionIndex}`,
          topicId: savedTopic.id,
          title: section.title,
          content: section.content,
          sortOrder: sectionIndex,
        },
      });
    }
  }

  console.log(`Seeded ${javaTopics.length} Java topics.`);
}

seedJava()
  .catch((error) => {
    console.error(error);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
